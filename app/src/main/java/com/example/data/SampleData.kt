    private val clothingTaxonomySubCategories: List<SubCategoryItem> by lazy {
        val result = mutableListOf<SubCategoryItem>()
        ClothingCatalogTaxonomy.clothingCategories.forEach { catSpec ->
            val parentId = categoryList.find {
                it.name.equals(catSpec.linkedMainCategoryName, ignoreCase = true)
            }?.id ?: catSpec.id
            catSpec.subcategories.forEachIndexed { idx, sub ->
                result.add(
                    SubCategoryItem(
                        id = sub.id,
                        parentCategory = catSpec.linkedMainCategoryName,
                        name = sub.name,
                        imageRes = sub.imageRes,
                        parentCategoryId = parentId,
                        seoName = "${catSpec.linkedMainCategoryName.lowercase().replace(Regex("[^a-z0-9]+"), "-")}-${sub.name.lowercase().replace(Regex("[^a-z0-9]+"), "-")}".trim('-'),
                        isActive = true,
                        sortOrder = idx + 1
                    )
                )
            }
        }
        result
    }

